import math


def area(a):
    '''
    принимает число a >= 0.
    возвращает квадрат числа a.

    прмиер вызова:
    S = area(8) // вернет 64.
    '''
    if a < 0:
        raise ValueError("Сторона квадрата не может быть отрицательной")
    return a * a


def perimeter(a):
    '''
    принимает число a >= 0.
    возвращает произведение 4 и a.

    пример вызова:
    P = perimeter(8) // вернет 32.
    '''
    if a < 0:
        raise ValueError("Сторона квадрата не может быть отрицательной")
    return 4 * a


