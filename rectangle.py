import math


def area(a,b):
    '''
    принимает два числа a и b.
    возвращает их произведение.

    пример вызова:
    S = area(3,4) // функция вернет 12
    '''
    return a*b

def perimeter(a,b):
    '''
    принимает два числа: a и b.
    возвращает удвоенное произведение их суммы.

    пример вызова:
    P = perimeter(5,4) // функция вернет 18
    '''
    return (a+b)*2


def diagonal(a, b):
    """Возвращает длину диагонали прямоугольника со сторонами a, b >= 0."""
    if a < 0 or b < 0:
        raise ValueError("Стороны прямоугольника не могут быть отрицательными")
    return math.hypot(a, b)