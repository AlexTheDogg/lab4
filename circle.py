import math


def area(r):
    '''
    Принимает число r >= 0.
    возвращает произведение квадрата r и числа пи из библиотеки math.

    пример вызова:
    S = area(5) // вернет 78.53981633974483
    '''
    if r < 0:
            raise ValueError("Радиус круга не может быть отрицательным")
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает число r >= 0.
    возвращает удвоенное произведение r и числа пи из библиотеки math.

    пример вызова:
    P = perimeter(5) // вернет 31.41592653589793
    '''
    if r < 0:
        raise ValueError("Радиус круга не может быть отрицательным")
    return 2 * math.pi * r
